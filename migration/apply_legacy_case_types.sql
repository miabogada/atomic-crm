INSERT INTO public.account_contract_case_types (contract_id, case_type_id)
SELECT ac.id, t.id
FROM public.account_contracts ac
JOIN legacy_case_type_map m ON m.legacy = ac.case_type
JOIN public.case_types t ON t.name = m.type_name
WHERE ac.deleted_at IS NULL
  AND NOT EXISTS (SELECT 1 FROM public.account_contract_case_types x WHERE x.contract_id = ac.id)  -- skip contracts already set via the new form
ON CONFLICT DO NOTHING;
COMMIT;
